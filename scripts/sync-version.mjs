#!/usr/bin/env node
/**
 * Single source of truth for versions: package.json "version" → android versionName, iOS
 * MARKETING_VERSION, src/core/env/version.generated.ts. Build numbers live in native files and are
 * bumped here with `--bump-build`. Run: `pnpm sync-version [--bump-build]`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const bump = process.argv.includes('--bump-build');

const gradlePath = path.join(root, 'android/app/build.gradle');
let gradle = readFileSync(gradlePath, 'utf8');
const vc = Number(/versionCode (\d+)/.exec(gradle)[1]) + (bump ? 1 : 0);
gradle = gradle
  .replace(/versionCode \d+/, `versionCode ${vc}`)
  .replace(/versionName "[^"]+"/, `versionName "${version}"`);
writeFileSync(gradlePath, gradle);

const pbxPath = path.join(root, 'ios/Lagnaa.xcodeproj/project.pbxproj');
let pbx = readFileSync(pbxPath, 'utf8');
const cpv = Number(/CURRENT_PROJECT_VERSION = (\d+);/.exec(pbx)[1]) + (bump ? 1 : 0);
pbx = pbx
  .replace(/CURRENT_PROJECT_VERSION = \d+;/g, `CURRENT_PROJECT_VERSION = ${cpv};`)
  .replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${version};`);
writeFileSync(pbxPath, pbx);

writeFileSync(
  path.join(root, 'src/core/env/version.generated.ts'),
  `// Generated by scripts/sync-version.mjs from package.json and the native projects. Do not edit.\nexport const APP_VERSION = '${version}';\nexport const BUILD_NUMBER = { ios: ${cpv}, android: ${vc} } as const;\n`,
);
console.log(`version ${version}; android versionCode ${vc}; ios build ${cpv}`);
