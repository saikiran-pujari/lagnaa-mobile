#!/usr/bin/env ruby
# Configures ios/Lagnaa.xcodeproj deterministically (run: `ruby scripts/ios-configure.rb`, idempotent):
#   - six build configurations: Debug/Release × Dev/Staging/Prod
#   - per-configuration bundle id, display name, LAGNAA_ENV, deployment target 16.0, entitlements
#   - three shared schemes: Lagnaa-Dev, Lagnaa-Staging, Lagnaa
#   - "Copy Firebase config" build phase (copies ios/Firebase/<Env>/GoogleService-Info.plist if present)
#   - BootSplash.storyboard and FirebaseBootstrap.swift added to the target
# Uses the xcodeproj gem bundled with CocoaPods.
require 'xcodeproj'

ROOT = File.expand_path('..', __dir__)
PROJECT_PATH = File.join(ROOT, 'ios', 'Lagnaa.xcodeproj')
ENVS = {
  'Dev' => { bundle: 'in.lagnaa.app.dev', name: 'Lagnaa Dev', scheme: 'Lagnaa-Dev' },
  'Staging' => { bundle: 'in.lagnaa.app.staging', name: 'Lagnaa Staging', scheme: 'Lagnaa-Staging' },
  'Prod' => { bundle: 'in.lagnaa.app', name: 'Lagnaa', scheme: 'Lagnaa' },
}.freeze

project = Xcodeproj::Project.open(PROJECT_PATH)
app_target = project.targets.find { |t| t.name == 'Lagnaa' } or abort('target Lagnaa not found')

# 1. Build configurations (project + target), cloned from the template's Debug/Release.
def ensure_config(project, list_owner, name, base_name)
  existing = list_owner.build_configuration_list.build_configurations.find { |c| c.name == name }
  return existing if existing
  base = list_owner.build_configuration_list.build_configurations.find { |c| c.name == base_name } or abort("base config #{base_name} missing")
  cfg = project.new(Xcodeproj::Project::Object::XCBuildConfiguration)
  cfg.name = name
  cfg.build_settings = base.build_settings.dup
  cfg.base_configuration_reference = base.base_configuration_reference
  list_owner.build_configuration_list.build_configurations << cfg
  cfg
end

ENVS.each do |env, meta|
  %w[Debug Release].each do |kind|
    name = "#{kind}-#{env}"
    ensure_config(project, project, name, kind)
    cfg = ensure_config(project, app_target, name, kind)
    cfg.build_settings['PRODUCT_BUNDLE_IDENTIFIER'] = meta[:bundle]
    cfg.build_settings['APP_DISPLAY_NAME'] = meta[:name]
    cfg.build_settings['LAGNAA_ENV'] = env
    cfg.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '16.0'
    cfg.build_settings['CODE_SIGN_ENTITLEMENTS'] = 'Lagnaa/Lagnaa.entitlements'
    cfg.build_settings['MARKETING_VERSION'] = '1.1.0'
    cfg.build_settings['CURRENT_PROJECT_VERSION'] = '1'
    cfg.build_settings['SWIFT_VERSION'] = '5.0'
    # The RN template keys DEBUG off the configuration *name*; our names carry an env suffix, so set it explicitly.
    cfg.build_settings['SWIFT_ACTIVE_COMPILATION_CONDITIONS'] = kind == 'Debug' ? '$(inherited) DEBUG' : '$(inherited)'
  end
end
project.build_configuration_list.build_configurations.each { |c| c.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '16.0' }

# Remove the template's plain Debug/Release once the six exist (CocoaPods maps the six).
[project, app_target].each do |owner|
  list = owner.build_configuration_list
  list.build_configurations.select { |c| %w[Debug Release].include?(c.name) }.each { |c| list.build_configurations.delete(c) }
  list.default_configuration_name = 'Release-Prod'
end

# 2b. Drop references whose file does not exist on disk (stale paths from earlier runs or tools), then
#     dedupe build files by basename (the bootsplash CLI and this script may both add the storyboard).
project.files.dup.each do |ref|
  next unless ref.path.to_s =~ /\.(swift|storyboard|entitlements)$/
  real = ref.real_path rescue nil
  ref.remove_from_project if real.nil? || !File.exist?(real.to_s)
end
[app_target.resources_build_phase, app_target.source_build_phase].each do |ph|
  seen = {}
  ph.files.dup.each do |bf|
    ref = bf.file_ref
    next unless ref
    key = File.basename(ref.path.to_s)
    if seen[key]
      ph.remove_build_file(bf)
      ref.remove_from_project
    else
      seen[key] = true
    end
  end
end

# 2. Source files: FirebaseBootstrap.swift and BootSplash.storyboard (generated by `pnpm bootsplash`).
group = project.main_group.find_subpath('Lagnaa', true)
def ensure_file(group, target, relative, kind)
  ref = group.files.find { |f| f.path == relative }
  unless ref
    ref = group.new_file(relative)
  end
  phase = kind == :source ? target.source_build_phase : target.resources_build_phase
  phase.add_file_reference(ref, true) unless phase.files_references.include?(ref)
  ref
end
ensure_file(group, app_target, 'Lagnaa/FirebaseBootstrap.swift', :source)
storyboard = File.join(ROOT, 'ios', 'Lagnaa', 'BootSplash.storyboard')
ensure_file(group, app_target, 'Lagnaa/BootSplash.storyboard', :resource) if File.exist?(storyboard)
group.files.find { |f| f.path == 'Lagnaa/Lagnaa.entitlements' } || group.new_file('Lagnaa/Lagnaa.entitlements')
# The template LaunchScreen is replaced by BootSplash.storyboard.
group.files.select { |f| f.path.to_s.end_with?('LaunchScreen.storyboard') }.each { |f| f.remove_from_project }

# 3. Copy Firebase config build phase (before Copy Bundle Resources).
PHASE_NAME = '[lagnaa] Copy Firebase config'
phase = app_target.shell_script_build_phases.find { |p| p.name == PHASE_NAME }
unless phase
  phase = app_target.new_shell_script_build_phase(PHASE_NAME)
  idx = app_target.build_phases.index(app_target.resources_build_phase)
  app_target.build_phases.delete(phase)
  app_target.build_phases.insert(idx, phase)
end
phase.shell_script = <<~'SH'
  SRC="${SRCROOT}/Firebase/${LAGNAA_ENV}/GoogleService-Info.plist"
  DST="${BUILT_PRODUCTS_DIR}/${PRODUCT_NAME}.app/GoogleService-Info.plist"
  if [ -f "$SRC" ]; then cp "$SRC" "$DST"; echo "lagnaa: bundled Firebase config for ${LAGNAA_ENV}"; else echo "lagnaa: no Firebase config for ${LAGNAA_ENV}; Firebase disabled"; fi
SH
phase.run_only_for_deployment_postprocessing = '0'

project.save

# 4. Schemes (shared).
schemes_dir = File.join(PROJECT_PATH, 'xcshareddata', 'xcschemes')
Dir.glob(File.join(schemes_dir, '*.xcscheme')).each { |f| File.delete(f) if File.basename(f, '.xcscheme') == 'Lagnaa' && !File.exist?(File.join(schemes_dir, 'Lagnaa.xcscheme.keep')) }
ENVS.each do |env, meta|
  scheme = Xcodeproj::XCScheme.new
  scheme.add_build_target(app_target)
  scheme.set_launch_target(app_target)
  scheme.build_action.parallelize_buildables = true
  scheme.launch_action.build_configuration = "Debug-#{env}"
  scheme.test_action.build_configuration = "Debug-#{env}"
  scheme.profile_action.build_configuration = "Release-#{env}"
  scheme.analyze_action.build_configuration = "Debug-#{env}"
  scheme.archive_action.build_configuration = "Release-#{env}"
  scheme.save_as(PROJECT_PATH, meta[:scheme], true)
end

puts "configured #{PROJECT_PATH}: configurations=#{app_target.build_configuration_list.build_configurations.map(&:name).join(', ')}"
puts "schemes: #{ENVS.values.map { |m| m[:scheme] }.join(', ')}"
